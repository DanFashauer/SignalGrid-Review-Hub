#!/usr/bin/env node
// gen-github-agent-profiles.mjs — the org roster's roles as GitHub Copilot custom-agent profiles.
//
//   node scripts/gen-github-agent-profiles.mjs --write      # regenerate .github/agents/*.agent.md
//   node scripts/gen-github-agent-profiles.mjs --check      # exit 1 if any profile is missing, stale or extra
//   node scripts/gen-github-agent-profiles.mjs --self-test  # prove --check can fail
//
// WHY. The repository has 42 canonical roles (docs/agent/org-roster.json) and GitHub's Agents
// tab shows none of them: GitHub reads custom agents from `.github/agents/<name>.agent.md`
// (docs.github.com, "Creating custom agents for Copilot cloud agent"). A handwritten copy of
// 42 roles would drift from the roster the day either changes, so the profiles are DERIVED.
//
// FAIL-CLOSED GRANTS. A profile is a grant on GitHub's side, and the local guards do not
// travel with it (the deny hooks and the sandbox that bound `Bash` here are not Copilot's).
//   - `tools` is ALWAYS written. GitHub reads an omitted `tools` as "all tools".
//   - Only documented aliases are used (read, search, edit). GitHub silently ignores an
//     unknown name, so a typo would change the grant without anyone seeing it.
//   - NO profile gets `execute`. Every local Bash grant is acceptable only behind the local
//     deny hooks and sandbox, and none of that travels to Copilot's environment. Whether a
//     GitHub-side agent should ever get a shell here is the owner's call, not a derivation.
//   - `agent:<name>` roles take their local agent's read/search/edit tools; a local agent
//     without Write/Edit is `read, search` only.
//   - `skill:<name>` and `lane` roles cannot run as a Copilot agent (Copilot loads neither a
//     .claude skill nor a lane). They get `tools: []` and `disable-model-invocation: true`,
//     and the body names the real executor. They describe the role; they run nothing.
//   - No `model`, no `mcp-servers`: either would grant something the roster never granted.
//   - Only stable roster fields are rendered (id, title, charter, trigger, surface, executor),
//     never `nextAction`/`nextActionDate`, which move weekly and would make every profile stale.
import { closeSync, constants, existsSync, fstatSync, mkdirSync, mkdtempSync, openSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isMainModule } from "./lib/is-main.mjs";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROSTER = "docs/agent/org-roster.json";
const OUT = ".github/agents";
const ALIASES = new Set(["read", "search", "edit"]);
const LOCAL_TO_ALIAS = { Read: "read", Grep: "search", Glob: "search", Edit: "edit", Write: "edit", Bash: "execute" };
const NAME = /^[a-z0-9][a-z0-9-]*$/;

/** The tools a role's profile may carry. Throws on anything it cannot map, never guesses. */
export function toolsFor(executor, localTools) {
  if (executor === "lane" || executor.startsWith("skill:")) return [];
  if (!executor.startsWith("agent:")) throw new Error(`unknown executor form: ${executor}`);
  if (!Array.isArray(localTools)) throw new Error(`no local tool list for ${executor}`);
  for (const t of localTools) if (!(t in LOCAL_TO_ALIAS)) throw new Error(`${executor}: local tool ${t} has no GitHub alias`);
  const mapped = new Set(localTools.map((t) => LOCAL_TO_ALIAS[t]));
  mapped.delete("execute"); // never on GitHub: see the header
  return ["read", "search", "edit"].filter((a) => mapped.has(a));
}

/** `tools:` line of a local .claude/agents/<name>.md file, as a list; null when absent. */
export function localToolsOf(markdown) {
  const front = /^---\n([\s\S]*?)\n---/.exec(markdown);
  if (!front) return null;
  const line = front[1].split("\n").find((l) => /^tools:/.test(l));
  return line ? line.replace(/^tools:\s*/, "").split(",").map((s) => s.trim()).filter(Boolean) : null;
}

const yamlString = (s) => JSON.stringify(String(s).replace(/\s+/g, " ").trim());

export function renderProfile(role, localTools) {
  if (!NAME.test(role.id)) throw new Error(`role id is not a valid profile file name: ${role.id}`);
  for (const k of ["title", "charter", "trigger", "executor"]) if (typeof role[k] !== "string" || !role[k].trim()) throw new Error(`${role.id}: missing ${k}`);
  const tools = toolsFor(role.executor, localTools);
  const runnable = role.executor.startsWith("agent:");
  const front = [
    "---",
    `name: ${role.id}`,
    `description: ${yamlString(`${role.title}. ${role.charter}`)}`,
    `tools: [${tools.map((t) => `"${t}"`).join(", ")}]`,
    ...(runnable ? [] : ["disable-model-invocation: true"]),
    "---",
  ];
  const surface = Array.isArray(role.surface) && role.surface.length ? role.surface.map((s) => `- \`${s}\``).join("\n") : "- (none declared)";
  const body = [
    `<!-- GENERATED by scripts/gen-github-agent-profiles.mjs from ${ROSTER}. Do not edit; edit the roster and run --write. -->`,
    "",
    `# ${role.title}`,
    "",
    `Canonical role \`${role.id}\` (${role.division}) in \`${ROSTER}\`.`,
    "",
    `**Charter.** ${role.charter}`,
    "",
    `**Called when.** ${role.trigger}`,
    "",
    "**Surface.**",
    surface,
    "",
    runnable
      ? `**Executor.** \`${role.executor}\` — the local definition \`.claude/agents/${role.executor.slice(6)}.md\` governs; this profile carries no grant beyond the tools listed above.${tools.includes("edit") ? "" : " Read-only: it reports and never edits."}`
      : `**Executor.** \`${role.executor}\` — this role runs as ${role.executor === "lane" ? "a lens of the working lane" : `the local skill \`.claude/skills/${role.executor.slice(6)}\``}, which Copilot cannot load. This profile describes the role only: no tools, never chosen automatically.`,
    "",
    "Follow the repository's CLAUDE.md and AGENTS.md: fail closed, report status truthfully, never bypass a check.",
    "",
  ];
  return front.join("\n") + "\n\n" + body.join("\n");
}

/** Every expected file → content, from the roster and the local agent definitions. */
export function expectedProfiles(roster, readAgent) {
  if (!roster || !Array.isArray(roster.roles) || roster.roles.length === 0) throw new Error("roster has no roles");
  const out = new Map();
  for (const role of roster.roles) {
    const local = role.executor?.startsWith("agent:") ? localToolsOf(readAgent(role.executor.slice(6)) ?? "") : null;
    const file = `${role.id}.agent.md`;
    if (out.has(file)) throw new Error(`two roles share id ${role.id}`);
    out.set(file, renderProfile(role, local));
  }
  return out;
}

/** Problems between expected profiles and what is on disk. Empty means in sync. */
export function diffProfiles(expected, actual) {
  const problems = [];
  for (const [f, body] of expected) {
    if (!actual.has(f)) problems.push(`missing ${OUT}/${f}`);
    else if (actual.get(f) !== body) problems.push(`stale ${OUT}/${f} (regenerate with --write)`);
  }
  for (const f of actual.keys()) if (!expected.has(f)) problems.push(`extra ${OUT}/${f} (no roster role)`);
  for (const [f, body] of actual) {
    const front = /^---\n([\s\S]*?)\n---/.exec(body)?.[1] ?? "";
    const line = front.split("\n").find((l) => /^tools:/.test(l));
    if (!line) { problems.push(`${OUT}/${f} has no tools line (GitHub would grant every tool)`); continue; }
    const names = [...line.matchAll(/"([^"]*)"/g)].map((m) => m[1]);
    for (const n of names) if (!ALIASES.has(n)) problems.push(`${OUT}/${f} grants an undocumented tool name: ${n}`);
  }
  return problems;
}

/** EVERY entry in the folder, not only `*.agent.md`: GitHub also reads plain `<name>.md` as a
 *  profile (and grants all tools when it has no `tools`), so anything else here must surface as
 *  an extra profile rather than be silently skipped. A non-file or symlink entry is recorded empty, which
 *  fails the tools check as well. */
export function readActual(dir) {
  const m = new Map();
  if (!existsSync(dir)) return m;
  for (const f of readdirSync(dir)) {
    // Open first, then inspect and read the SAME descriptor: no check-then-use window, and a
    // symbolic link is refused rather than followed.
    let fd = null, body = "";
    try {
      fd = openSync(join(dir, f), constants.O_RDONLY | constants.O_NOFOLLOW);
      if (fstatSync(fd).isFile()) body = readFileSync(fd, "utf8");
    } catch { body = ""; }
    finally { if (fd !== null) closeSync(fd); }
    m.set(f, body);
  }
  return m;
}

function load(root = repo) {
  const roster = JSON.parse(readFileSync(join(root, ROSTER), "utf8"));
  const readAgent = (n) => { const p = join(root, ".claude/agents", `${n}.md`); return existsSync(p) ? readFileSync(p, "utf8") : null; };
  return expectedProfiles(roster, readAgent);
}

/** For a gate that already runs: every problem with the checked-in profiles, or a refusal. */
export function profileProblems(root = repo) {
  try { return diffProfiles(load(root), readActual(join(root, OUT))); }
  catch (err) { return [`GitHub agent profiles cannot be derived: ${err.message}`]; }
}

/** The behavioural refusal cases, as [name, ok] pairs, for this CLI and for the roster gate's self-test. */
export function profileSelfTestChecks() {
  const checks = [];
  const role = (o) => ({ id: "r1", division: "engineering", title: "T", charter: "C", trigger: "X", executor: "lane", surface: ["a/**"], ...o });
  const exp = expectedProfiles({ roles: [role({}), role({ id: "r2", executor: "agent:reader" }), role({ id: "r3", executor: "agent:writer" })] },
    (n) => (n === "reader" ? "---\ntools: Read, Grep, Glob, Bash\n---\n" : n === "writer" ? "---\ntools: Read, Write, Edit, Bash, Grep, Glob\n---\n" : null));
  checks.push(["a lane role carries tools: [] and is never chosen automatically", /tools: \[\]\ndisable-model-invocation: true/.test(exp.get("r1.agent.md"))]);
  checks.push(["a read-only local agent is read-only on GitHub: read and search, never execute", /tools: \["read", "search"\]\n---/.test(exp.get("r2.agent.md"))]);
  checks.push(["a writing local agent maps to read, search, edit, and still never execute", /tools: \["read", "search", "edit"\]\n/.test(exp.get("r3.agent.md")) && !/execute/.test(exp.get("r3.agent.md").split("---")[1])]);
  checks.push(["in sync is no problem", diffProfiles(exp, new Map(exp)).length === 0]);
  const missing = new Map(exp); missing.delete("r2.agent.md");
  checks.push(["a roster role with no profile is a problem", diffProfiles(exp, missing).some((p) => p.startsWith("missing"))]);
  const stale = new Map(exp); stale.set("r1.agent.md", exp.get("r1.agent.md") + "x");
  checks.push(["a hand-edited profile is stale", diffProfiles(exp, stale).some((p) => p.startsWith("stale"))]);
  const extra = new Map(exp); extra.set("ghost.agent.md", exp.get("r1.agent.md"));
  checks.push(["a profile with no roster role is extra", diffProfiles(exp, extra).some((p) => p.startsWith("extra"))]);
  const noTools = new Map(exp); noTools.set("r1.agent.md", exp.get("r1.agent.md").replace(/tools: \[\]\n/, ""));
  checks.push(["a profile without a tools line is refused (GitHub would grant all tools)", diffProfiles(exp, noTools).some((p) => /no tools line/.test(p))]);
  const typo = new Map(exp); typo.set("r3.agent.md", exp.get("r3.agent.md").replace('"edit"]', '"edit", "execute"]'));
  checks.push(["a hand-added execute grant is refused as an undocumented tool name", diffProfiles(exp, typo).some((p) => /undocumented tool name: execute/.test(p))]);
  // The real folder reader, on a disposable folder: a plain .md profile with no tools is caught.
  const tmp = mkdtempSync(join(tmpdir(), "agent-profiles-"));
  try {
    for (const [f, body] of exp) writeFileSync(join(tmp, f), body);
    writeFileSync(join(tmp, "unrestricted.md"), "---\nname: unrestricted\ndescription: x\n---\n");
    const found = diffProfiles(exp, readActual(tmp));
    checks.push(["a plain .md profile in the folder is reported extra and tool-less, never skipped",
      found.includes(`extra ${OUT}/unrestricted.md (no roster role)`) && found.some((p) => /unrestricted\.md has no tools line/.test(p))]);
  } finally { rmSync(tmp, { recursive: true, force: true }); }
  let threw = false; try { toolsFor("agent:x", ["Read", "WebFetch"]); } catch { threw = true; }
  checks.push(["a local tool with no GitHub alias refuses instead of guessing", threw]);
  threw = false; try { expectedProfiles({ roles: [role({ executor: "agent:none" })] }, () => null); } catch { threw = true; }
  checks.push(["an agent role whose local definition has no tools line refuses", threw]);
  return checks;
}

function selfTest() {
  const checks = profileSelfTestChecks();
  const failed = checks.filter(([, ok]) => !ok);
  for (const [n, ok] of checks) console.log(`  ${ok ? "ok" : "FAIL"} — ${n}`);
  console.log(`self-test ${failed.length ? "FAILED" : "passed"} (${checks.length - failed.length}/${checks.length})`);
  return failed.length ? 1 : 0;
}

if (isMainModule(process.argv[1], import.meta.url)) {
  if (process.argv.includes("--self-test")) process.exit(selfTest());
  const expected = load();
  const dir = join(repo, OUT);
  if (process.argv.includes("--write")) {
    mkdirSync(dir, { recursive: true });
    for (const f of readActual(dir).keys()) if (!expected.has(f)) rmSync(join(dir, f));
    for (const [f, body] of expected) writeFileSync(join(dir, f), body);
    console.log(`wrote ${expected.size} profile(s) to ${OUT}`);
  } else {
    const problems = diffProfiles(expected, readActual(dir));
    if (problems.length) {
      console.error(`GitHub agent profiles FAILED: ${problems.length} problem(s).`);
      for (const p of problems.slice(0, 25)) console.error(`  ✗ ${p}`);
      process.exit(1);
    }
    console.log(`GitHub agent profiles in sync — ${expected.size} role(s), every profile states its tools.`);
  }
}
