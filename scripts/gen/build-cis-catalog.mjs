#!/usr/bin/env node
// Regenerate the committed CIS catalog snapshot from a raw public-catalog export.
//
//   node scripts/gen/build-cis-catalog.mjs <raw-export.json>
//
// The raw export is a listing of the PUBLIC CIS Benchmarks catalog page: one record
// per benchmark/version with { family, benchmark, version, catalog_section }.
//
// WHAT THIS EMITS, AND WHAT IT REFUSES TO EMIT. Titles, versions, and the
// family/section a row is filed under — factual catalog metadata. CIS benchmark
// RULE CONTENT (control text, rationale, audit and remediation procedures) is
// licensed by CIS and is never written here; the loader independently refuses any
// value carrying control-statement grammar, so a careless refresh fails loudly
// rather than quietly publishing licensed text.
//
// TITLE IS THE IDENTITY. Version standing is computed per title, never per family:
// the catalog files "Microsoft Windows Server 2019 STIG" v3.0.0 under family
// "Microsoft Windows Server" and its successor v4.0.0 under family "DISA STIG", so
// a family-keyed model reports the superseded row as current. Measured: it hides 3
// of the 7 superseded rows.
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("usage: build-cis-catalog.mjs <raw-export.json>");
  process.exit(2);
}
const raw = JSON.parse(readFileSync(src, "utf8"));
const vt = (v) => v.split(".").map(Number);
const greater = (a, b) => {
  const [a0, a1, a2] = vt(a);
  const [b0, b1, b2] = vt(b);
  if (a0 !== b0) return a0 > b0;
  if (a1 !== b1) return a1 > b1;
  return a2 > b2;
};

const rows = raw.benchmarks.map((x) => ({
  title: x.benchmark,
  version: x.version,
  family: x.family,
  section: String(x.catalog_section).endsWith("DISA STIG") ? "disa_stig" : "current",
}));
rows.sort((a, b) => (a.title === b.title ? (greater(a.version, b.version) ? 1 : -1) : a.title < b.title ? -1 : 1));

const byTitle = new Map();
for (const r of rows) byTitle.set(r.title, [...(byTitle.get(r.title) ?? []), r.version]);
const highestOf = (t) => byTitle.get(t).reduce((best, v) => (greater(v, best) ? v : best));
const highestRows = rows.filter((r) => r.version === highestOf(r.title)).length;

const derived = {
  entries: rows.length,
  titles: byTitle.size,
  titlesWithMultipleVersions: [...byTitle.values()].filter((v) => v.length > 1).length,
  highestVersionRows: highestRows,
  supersededRows: rows.length - highestRows,
  families: new Set(rows.map((r) => r.family)).size,
  sectionCurrent: rows.filter((r) => r.section === "current").length,
  sectionDisaStig: rows.filter((r) => r.section === "disa_stig").length,
};

const out = `// GENERATED by scripts/gen/build-cis-catalog.mjs — do not hand-edit.
//
// A dated snapshot of the PUBLIC CIS Benchmarks catalog listing: benchmark titles,
// version strings, and the family/section each row is filed under. Factual catalog
// metadata only.
//
// CIS benchmark RULE CONTENT — control text, rationale, audit and remediation
// procedures — is licensed by CIS and is deliberately NOT reproduced here.
// SignalGrid performs no benchmark assessment and claims no CIS certification,
// conformance, or partnership.
//
// TITLE is the benchmark's identity; version standing is computed per title.
// \`family\` and \`section\` are the catalog page's presentation buckets and are
// carried as evidence only — see catalog.ts for why keying identity on them is
// measurably wrong.
//
// The \`derived\` block is a CLAIM. catalog.ts re-derives every figure from the
// entries and refuses the snapshot on any disagreement.

export interface CisCatalogSnapshot {
  readonly schema: "signalgrid-cis-benchmark-catalog/v1";
  readonly asOf: string;
  readonly derived: Readonly<Record<string, number>>;
  readonly entries: readonly { readonly title: string; readonly version: string; readonly family: string; readonly section: string }[];
}

export const CIS_CATALOG_SNAPSHOT: CisCatalogSnapshot = {
  schema: "signalgrid-cis-benchmark-catalog/v1",
  asOf: ${JSON.stringify(raw.as_of)},
  derived: ${JSON.stringify(derived, null, 4).replace(/\n/g, "\n  ")},
  entries: [
${rows.map((r) => `    { title: ${JSON.stringify(r.title)}, version: ${JSON.stringify(r.version)}, family: ${JSON.stringify(r.family)}, section: ${JSON.stringify(r.section)} },`).join("\n")}
  ],
};
`;
writeFileSync("lib/integrations/src/integrations/benchmark-selection/cis-catalog.data.ts", out);
console.error(`wrote ${rows.length} entries; derived ${JSON.stringify(derived)}`);
